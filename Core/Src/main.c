/**
 * @brief  Коллбэк приема данных по UART через DMA (по событию IDLE - линия свободна).
 * @note   Используется для приема пакетов от Лидара (USART3). Срабатывает, когда пакет принят целиком.
 */
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
	if(huart->Instance != USART3){
		return;
	}
    // Если размер в рамках буфера и мы успели обработать прошлый пакет (RxIdle == 0)
	if (Size <= sizeof(raw_data) && !RxIdle)
	{
	    memcpy(raw_data, arr, Size); // Копируем сырые данные для безопасного парсинга
	    sizeIdle = Size;
	    RxIdle = 1; // Поднимаем флаг для обработки в main-цикле
	}
    // Перезапускаем прием DMA до следующего события IDLE
	HAL_UARTEx_ReceiveToIdle_DMA(&huart3, arr, sizeof(arr));
}


